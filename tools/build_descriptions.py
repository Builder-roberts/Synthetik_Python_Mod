"""Regenerates ui_descriptions.py from saved SYNTHETIK-wiki pages (the 4 class pages + Artifacts).

    python tools/build_descriptions.py <folder with the *_-_SYNTHETIK_Wiki*.htm files>

Module / artefact cards (div.name + div.description), the "core: X" blocks, each class's
signature item and the rows of the Items table are matched to game object ids by display
name (see ui_icons.CATALOG).
"""
import glob
import html
import os
import re
import sys

sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
import ui_icons as I  # noqa: E402

SIGNATURE = {  # a class page's first item card is named after the class; this is the item it describes
    "Engineer": "LMG Sentry Turret", "Raider": "Reverbing Blade", "Riot Guard": "Battlecry Module",
    "Sniper": "Targeting Laser", "Demolisher": "Seismic Resonator", "Heavy Gunner": "Onslaught System",
    "Assassin": "Scoundrel's Dagger", "Breacher": "Breaching Charge",
}
CORES = {"drone zeal": "obj_perk_engineer", "looter": "obj_perk_raider", "spotter": "obj_perk_marksman",
         "unyielding": "obj_perk_riotguard", "he-ammo": "obj_perk_demolisher", "suppression": "obj_perk_assaultgunner",
         "professional": "obj_perk_assassin", "charge": "obj_perk_breacher"}


def clean(raw):
    raw = raw.replace("<br><br>", "\n").replace("<br>", " ")
    text = html.unescape(re.sub(r"<[^>]+>", "", raw))
    text = re.sub(r"\[([^\]]*)\]", r"\1", text)  # "[35%]" -> "35%"
    return "\n".join(re.sub(r"[ \t]+", " ", line).strip() for line in text.split("\n")).strip()


def main(folder):
    by_norm = {I._norm(m.display): m for m in I.CATALOG}
    by_norm.update({I._norm(m.name): m for m in I.CATALOG})
    out, missed = {}, []
    for path in sorted(glob.glob(os.path.join(folder, "*SYNTHETIK_Wiki*.htm"))):
        page = open(path, errors="ignore").read()
        cards = re.split(r'<div class="info-box flashcard item', page)[1:]
        for card in cards:
            name_m = re.search(r'<div class="name">(.*?)</div>', card, re.S)
            desc_m = re.search(r'<div class="description">(.*?)</div>', card, re.S)
            if not (name_m and desc_m):
                continue
            name = " ".join(html.unescape(re.sub(r"<[^>]+>", " ", name_m.group(1))).split())
            name = SIGNATURE.get(name, name)
            info = by_norm.get(I._norm(name))
            if info is None:
                missed.append(name)
            else:
                out.setdefault(info.obj_id, clean(desc_m.group(1)))
        for m in re.finditer(r'<div class="name">core: (.*?)</div>\s*<div class="container">(.*?)</div>', page, re.S):
            key = m.group(1).strip().lower()
            if key in CORES:
                out.setdefault(CORES[key], clean(m.group(2)))
        # Items page: | icon | <b>name</b> | rarity | description | cooldown | notes |
        for m in re.finditer(r"<td><center><b>(.*?)</b></center>\s*</td>\s*<td><center>(.*?)</center>\s*</td>\s*"
                             r"<td>(.*?)</td>\s*<td>(.*?)</td>", page, re.S):
            name = " ".join(html.unescape(re.sub(r"<[^>]+>", " ", m.group(1))).split())
            info = by_norm.get(I._norm(name))
            if info is not None and info.kind in ("item", "random"):
                text = clean(m.group(3))
                cooldown = " ".join(re.sub(r"<[^>]+>", " ", m.group(4)).split())
                if cooldown:
                    text += f"\nCooldown: {cooldown}"
                out.setdefault(info.obj_id, text)
    order = {m.obj_id: m.index for m in I.CATALOG}
    with open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "ui_descriptions.py"), "w", encoding="utf-8") as f:
        f.write('"""ui_descriptions.py - hover-tooltip text, generated by tools/build_descriptions.py\n'
                'from the SYNTHETIK wiki (class pages + Artifacts).  Keyed by game object id."""\n\nDESCRIPTIONS = {\n')
        for obj_id in sorted(out, key=lambda k: order.get(k, 0)):
            f.write(f"    {obj_id!r}: {out[obj_id]!r},\n")
        f.write("}\n")
    print(f"{len(out)} descriptions written; unmatched cards: {missed}")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else ".")
